pub(super) fn digest(bytes: &[u8]) -> String {
    ring::digest::digest(&ring::digest::SHA256, bytes)
        .as_ref()
        .iter()
        .map(|x| format!("{x:02x}"))
        .collect()
}

pub(super) fn validate_path(path: &str) -> Result<String, Error> {
    if path == "/"
        || !path.starts_with('/')
        || path.as_bytes().contains(&0)
        || path.contains('\n')
        || Path::new(path)
            .components()
            .any(|x| !matches!(x, Component::RootDir | Component::Normal(_)))
    {
        return Err(
            "select an absolute application configuration path without parent components".into(),
        );
    }
    Ok(Path::new(path)
        .components()
        .collect::<PathBuf>()
        .display()
        .to_string())
}

// Runtime identity/proxy material is regenerated by existing boot owners.
pub(super) fn excluded(path: &str) -> bool {
    let fixed = [
        "/etc/.gitignore",
        "/etc/environment",
        "/etc/resolv.conf",
        "/etc/hostname",
        "/etc/hosts",
        "/etc/machine-id",
        "/etc/ssl/certs/safeyolo.pem",
        "/etc/passwd",
        "/etc/shadow",
        "/etc/group",
        "/etc/gshadow",
        "/etc/mtab",
        "/etc/safeyolo-mise-environment",
        "/etc/profile.d/safeyolo-proxy.sh",
        "/etc/apt/apt.conf.d/99safeyolo-proxy",
        "/usr/local/share/ca-certificates/safeyolo.crt",
        "/app/agent_token",
        "/safeyolo",
        "/safeyolo-status",
        "/proc",
        "/sys",
        "/dev",
        "/run",
        "/tmp",
        "/var/cache",
        "/var/log",
        "/var/lib/dpkg",
    ];
    fixed
        .iter()
        .any(|x| path == *x || path.starts_with(&format!("{x}/")))
        || path
            .split('/')
            .any(|x| matches!(x, ".git" | ".etckeeper" | ".hg" | ".bzr"))
        || path.starts_with("/etc/ssh/ssh_host_")
}

fn describe(path: &Path) -> Result<Option<Value>, Error> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(value) => value,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(error.into()),
    };
    let kind = metadata.file_type();
    let data = if kind.is_file() {
        let mut context = ring::digest::Context::new(&ring::digest::SHA256);
        let mut file = fs::File::open(path)?;
        let mut buffer = [0; 65536];
        loop {
            let n = file.read(&mut buffer)?;
            if n == 0 {
                break;
            }
            context.update(&buffer[..n]);
        }
        json!({"kind":"file","hash":context.finish().as_ref().iter().map(|x| format!("{x:02x}")).collect::<String>()})
    } else if kind.is_symlink() {
        json!({"kind":"symlink","target":fs::read_link(path)?})
    } else if kind.is_dir() {
        json!({"kind":"directory"})
    } else {
        return Err(format!("unsupported configuration file type: {}", path.display()).into());
    };
    let mut data = data;
    data["mode"] = json!(metadata.mode() & 0o7777);
    data["uid"] = json!(metadata.uid());
    data["gid"] = json!(metadata.gid());
    Ok(Some(data))
}

fn walk(root: &Path, path: &str, files: &mut Map<String, Value>) -> Result<(), Error> {
    if excluded(path) {
        return Ok(());
    }
    let actual = root.join(path.trim_start_matches('/'));
    let Some(value) = describe(&actual)? else {
        return Ok(());
    };
    let directory = value["kind"] == "directory";
    files.insert(path.into(), value);
    if directory {
        let mut children = fs::read_dir(actual)?.collect::<Result<Vec<_>, _>>()?;
        children.sort_by_key(|x| x.file_name());
        for child in children {
            let name = child
                .file_name()
                .into_string()
                .map_err(|_| "configuration filename is not UTF-8")?;
            walk(
                root,
                &format!("{}/{name}", path.trim_end_matches('/')),
                files,
            )?;
        }
    }
    Ok(())
}

pub(super) fn inventory(root: &Path, paths: &[String]) -> Result<Value, Error> {
    let mut files = Map::new();
    for path in paths {
        validate_path(path)?;
        walk(root, path, &mut files)?;
    }
    Ok(Value::Object(files))
}

fn account_names(root: &Path) -> Result<(Map<String, Value>, Map<String, Value>), Error> {
    let mut result = (Map::new(), Map::new());
    for (filename, names) in [("etc/passwd", &mut result.0), ("etc/group", &mut result.1)] {
        let text = match fs::read_to_string(root.join(filename)) {
            Ok(text) => text,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => String::new(),
            Err(error) => return Err(error.into()),
        };
        for line in text.lines() {
            let fields: Vec<_> = line.split(':').collect();
            if fields.len() >= 3 {
                names.insert(fields[2].into(), json!(fields[0]));
            }
        }
    }
    Ok(result)
}

fn accounts(state: &Value, names: &(Map<String, Value>, Map<String, Value>)) -> Value {
    json!({"user":names.0.get(&state["uid"].to_string()),"group":names.1.get(&state["gid"].to_string())})
}

fn copy_file(source: &Path, target: &Path, value: &Value) -> Result<(), Error> {
    if value["kind"] == "directory" {
        if target.symlink_metadata().is_ok_and(|meta| !meta.is_dir()) {
            remove(target)?;
        }
        fs::create_dir_all(target)?;
    } else {
        fs::create_dir_all(target.parent().ok_or("configuration path has no parent")?)?;
        // Replace the copy, never follow an old symlink in the recovery mirror.
        if target.symlink_metadata().is_ok() {
            remove(target)?;
        }
        output(
            Command::new("cp")
                .args([
                    "--no-dereference",
                    "--preserve=mode,ownership,timestamps",
                    "--",
                ])
                .arg(source)
                .arg(target),
        )?;
    }
    metadata(target, value)?;
    if value["kind"] != "symlink" {
        fs::File::open(target)?.sync_all()?;
    }
    if let Some(parent) = target.parent() {
        fs::File::open(parent)?.sync_all()?;
    }
    Ok(())
}

fn metadata(path: &Path, value: &Value) -> Result<(), Error> {
    use std::{ffi::CString, os::unix::ffi::OsStrExt};
    let name = CString::new(path.as_os_str().as_bytes())?;
    let uid = value["uid"].as_u64().ok_or("missing uid")? as u32;
    let gid = value["gid"].as_u64().ok_or("missing gid")? as u32;
    if unsafe { libc::lchown(name.as_ptr(), uid, gid) } != 0 {
        return Err(std::io::Error::last_os_error().into());
    }
    if value["kind"] != "symlink" {
        fs::set_permissions(
            path,
            fs::Permissions::from_mode(value["mode"].as_u64().ok_or("missing mode")? as u32),
        )?;
    }
    Ok(())
}

fn remove(path: &Path) -> Result<(), Error> {
    let meta = fs::symlink_metadata(path)?;
    if meta.is_dir() {
        fs::remove_dir(path)?;
    } else {
        fs::remove_file(path)?;
    }
    Ok(())
}

fn etckeeper(directory: &Path, command: &str) -> Result<(), Error> {
    let mut process = Command::new("etckeeper");
    process.arg(command).arg("-d").arg(directory);
    if command == "commit" {
        process.arg("guest configuration capture");
    }
    output(
        process
            .env("GIT_AUTHOR_NAME", "SafeYolo guest")
            .env("GIT_AUTHOR_EMAIL", "guest@localhost")
            .env("GIT_COMMITTER_NAME", "SafeYolo guest")
            .env("GIT_COMMITTER_EMAIL", "guest@localhost"),
    )?;
    Ok(())
}

// A killed capture can leave the working mirror ahead of the acknowledged
// record. Git's completed commit, rather than those partial copies, owns recovery.
fn completed_mirror(store: &GuestState, value: &Value) -> Result<(), Error> {
    let Some(commit) = value["configuration_commit"].as_str() else {
        return Ok(());
    };
    let mirror = store.directory.join("configuration");
    output(
        Command::new("git")
            .arg("-C")
            .arg(&mirror)
            .args(["reset", "--hard", commit]),
    )?;
    output(
        Command::new("git")
            .arg("-C")
            .arg(&mirror)
            .args(["clean", "-fdx"]),
    )?;
    for (path, state) in value["configuration"]
        .as_object()
        .ok_or("invalid configuration")?
    {
        let target = mirror.join(path.trim_start_matches('/'));
        if state["kind"] == "directory" {
            fs::create_dir_all(&target)?;
        }
        metadata(&target, state)?;
    }
    let mut recorded_paths: Vec<String> = Vec::new();
    for path in value["configuration"]
        .as_object()
        .ok_or("invalid configuration")?
        .keys()
    {
        if !recorded_paths
            .iter()
            .any(|root| path == root || path.starts_with(&format!("{root}/")))
        {
            recorded_paths.push(path.clone());
        }
    }
    if inventory(&mirror, &recorded_paths)? != value["configuration"] {
        return Err("completed configuration history does not match the retained record".into());
    }
    Ok(())
}

fn record_commit(store: &GuestState, value: &mut Value) -> Result<(), Error> {
    value["configuration_commit"] = json!(
        output(
            Command::new("git")
                .arg("-C")
                .arg(store.directory.join("configuration"))
                .args(["rev-parse", "HEAD"])
        )?
        .trim()
    );
    Ok(())
}

pub(super) fn validate_coverage(store: &GuestState, paths: &[String]) -> Result<(), Error> {
    if paths
        .iter()
        .any(|path| store.directory.starts_with(store.actual(path)))
    {
        return Err("coverage contains the recorder's persistent directory; choose an application configuration path".into());
    }
    let state_path = store.directory.canonicalize()?;
    for path in paths {
        if let Ok(actual) = store.actual(path).canonicalize()
            && (state_path.starts_with(&actual) || actual.starts_with(&state_path))
        {
            return Err("configuration coverage overlaps recorder bookkeeping".into());
        }
    }
    Ok(())
}

pub(super) fn capture(store: &GuestState, value: &mut Value) -> Result<(), Error> {
    let paths = coverage(value)?;
    validate_coverage(store, &paths)?;
    completed_mirror(store, value)?;
    let files = inventory(&store.root, &paths)?;
    let mut previous = value["configuration"]
        .as_object()
        .ok_or("invalid configuration inventory")?
        .clone();
    let mirror = store.directory.join("configuration");
    fs::create_dir_all(&mirror)?;
    fs::set_permissions(&mirror, fs::Permissions::from_mode(0o700))?;
    for (path, state) in inventory(&mirror, &paths)?
        .as_object()
        .ok_or("invalid configuration mirror")?
    {
        previous.insert(path.clone(), state.clone());
    }
    let current = files.as_object().ok_or("invalid configuration snapshot")?;
    // Children before parents on deletion; a nonempty directory refuses instead of deleting user data.
    let mut removed: Vec<_> = previous
        .keys()
        .filter(|x| !current.contains_key(*x))
        .collect();
    removed.sort_by_key(|x| std::cmp::Reverse(x.len()));
    for path in removed {
        let target = mirror.join(path.trim_start_matches('/'));
        if target.symlink_metadata().is_ok() {
            remove(&target)?;
        }
    }
    for (path, state) in current {
        if previous.get(path) != Some(state) || !mirror.join(path.trim_start_matches('/')).exists()
        {
            copy_file(
                &store.actual(path),
                &mirror.join(path.trim_start_matches('/')),
                state,
            )?;
        }
    }
    if inventory(&mirror, &paths)? != files {
        return Err("configuration changed during capture; retry after writes settle".into());
    }
    commit_history(&mirror)?;
    let names = account_names(&store.root)?;
    value["configuration_accounts"] = json!(
        files
            .as_object()
            .ok_or("invalid configuration")?
            .iter()
            .map(|(path, state)| (path.clone(), accounts(state, &names)))
            .collect::<Map<String, Value>>()
    );
    value["configuration"] = files;
    record_commit(store, value)?;
    Ok(())
}

fn commit_history(mirror: &Path) -> Result<(), Error> {
    if !mirror.join(".git").exists() {
        etckeeper(mirror, "init")?;
        for (name, setting) in [("core.fsync", "committed"), ("commit.gpgsign", "false")] {
            output(
                Command::new("git")
                    .arg("-C")
                    .arg(mirror)
                    .args(["config", name, setting]),
            )?;
        }
    }
    etckeeper(mirror, "pre-commit")?;
    output(
        Command::new("git")
            .arg("-C")
            .arg(mirror)
            .args(["add", "--force", "--all", "."]),
    )?;
    let status = Command::new("git")
        .arg("-C")
        .arg(mirror)
        .args(["diff", "--cached", "--quiet"])
        .status()?;
    match status.code() {
        Some(0) => (),
        Some(1) => etckeeper(mirror, "commit")?,
        _ => return Err("cannot inspect configuration history index".into()),
    }
    Ok(())
}

pub(super) fn resolve(store: &GuestState, value: &mut Value, path: &str) -> Result<(), Error> {
    let selected = validate_path(path)?;
    let path = selected.as_str();
    if excluded(path)
        || !coverage(value)?
            .iter()
            .any(|root| path == root || path.starts_with(&format!("{root}/")))
    {
        return Err("select a covered configuration file to retain its reviewed resolution".into());
    }
    safe_parents(&store.root, path)?;
    completed_mirror(store, value)?;
    let mirror = store.directory.join("configuration");
    let target = mirror.join(path.trim_start_matches('/'));
    if let Some(state) = describe(&store.actual(path))? {
        copy_file(&store.actual(path), &target, &state)?;
        value["configuration_accounts"][path] = accounts(&state, &account_names(&store.root)?);
        value["configuration"][path] = state;
    } else {
        if target.symlink_metadata().is_ok() {
            remove(&target)?;
        }
        value["configuration"]
            .as_object_mut()
            .ok_or("invalid configuration")?
            .remove(path);
    }
    commit_history(&mirror)?;
    record_commit(store, value)?;
    store.save(value)
}

fn safe_parents(root: &Path, path: &str) -> Result<(), Error> {
    let target = root.join(path.trim_start_matches('/'));
    for parent in target.ancestors().skip(1) {
        if parent == root {
            break;
        }
        match parent.symlink_metadata() {
            Ok(meta) if meta.file_type().is_symlink() => {
                return Err(
                    format!("configuration parent is a symlink: {}", parent.display()).into(),
                );
            }
            Ok(_) => (),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => (),
            Err(error) => return Err(error.into()),
        }
    }
    Ok(())
}

pub(super) fn restore(store: &GuestState, value: &mut Value, apply: bool) -> Result<(), Error> {
    completed_mirror(store, value)?;
    let old = value["baseline"]
        .as_object()
        .ok_or("missing original baseline")?;
    let saved = value["configuration"]
        .as_object()
        .ok_or("missing captured configuration")?
        .clone();
    let paths = coverage(value)?;
    let account_names = account_names(&store.root)?;
    let mut changes = Vec::new();
    let mut conflicts = Vec::new();
    let all: BTreeSet<_> = old.keys().chain(saved.keys()).collect();
    for path in all {
        if excluded(path)
            || !paths
                .iter()
                .any(|x| path == x || path.starts_with(&format!("{x}/")))
        {
            continue;
        }
        let before = old.get(path);
        let wanted = saved.get(path);
        if before == wanted {
            continue;
        }
        safe_parents(&store.root, path)?;
        let actual = describe(&store.actual(path))?;
        if let Some(wanted) = wanted
            && !value["configuration_accounts"][path].is_null()
            && value["configuration_accounts"][path] != accounts(wanted, &account_names)
        {
            conflicts.push(path.clone());
            continue;
        }
        if actual.as_ref() == wanted {
            continue;
        }
        if actual.as_ref() != before {
            conflicts.push(path.clone());
            continue;
        }
        changes.push((path.clone(), wanted.cloned()));
    }
    value["restore"]["configuration_changes"] =
        json!(changes.iter().map(|x| &x.0).collect::<Vec<_>>());
    value["restore"]["configuration_conflicts"] = json!(conflicts);
    store.save(value)?;
    println!("{}", value["restore"]);
    if !conflicts.is_empty() {
        return Err("configuration conflicts need review; retained files were preserved".into());
    }
    if apply {
        // Directory creation and file changes precede directory removals.
        changes.sort_by_key(|(path, state)| {
            (
                state.is_none(),
                if state.is_some() {
                    path.len()
                } else {
                    usize::MAX - path.len()
                },
            )
        });
        for (path, state) in changes {
            let target = store.actual(&path);
            if let Some(state) = state {
                copy_file(
                    &store
                        .directory
                        .join("configuration")
                        .join(path.trim_start_matches('/')),
                    &target,
                    &state,
                )?;
            } else if target.symlink_metadata().is_ok() {
                remove(&target)?;
            }
        }
        // Verify the result, including ownership and permissions, before acknowledging it.
        for path in value["restore"]["configuration_changes"]
            .as_array()
            .ok_or("missing restore paths")?
        {
            let path = path.as_str().ok_or("invalid restore path")?;
            if describe(&store.actual(path))?.as_ref() != saved.get(path) {
                return Err(format!("configuration restore verification failed: {path}").into());
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn three_way_restore_preserves_new_defaults_and_exposes_conflicts() {
        let temporary = tempfile::tempdir().unwrap();
        let root = temporary.path().join("root");
        let store = GuestState {
            root: root.clone(),
            directory: temporary.path().join("saved"),
        };
        fs::create_dir_all(root.join("etc")).unwrap();
        fs::create_dir_all(&store.directory).unwrap();
        fs::write(root.join("etc/edit"), "base\n").unwrap();
        fs::write(root.join("etc/delete"), "remove locally\n").unwrap();
        let baseline = inventory(&root, &["/etc".into()]).unwrap();
        fs::write(root.join("etc/edit"), "local\n").unwrap();
        fs::set_permissions(root.join("etc/edit"), fs::Permissions::from_mode(0o600)).unwrap();
        fs::remove_file(root.join("etc/delete")).unwrap();
        let desired = inventory(&root, &["/etc".into()]).unwrap();
        for (path, state) in desired.as_object().unwrap() {
            copy_file(
                &store.actual(path),
                &store
                    .directory
                    .join("configuration")
                    .join(path.trim_start_matches('/')),
                state,
            )
            .unwrap();
        }
        fs::write(root.join("etc/edit"), "base\n").unwrap();
        fs::set_permissions(root.join("etc/edit"), fs::Permissions::from_mode(0o644)).unwrap();
        fs::write(root.join("etc/delete"), "remove locally\n").unwrap();
        fs::write(root.join("etc/new-security-default"), "new\n").unwrap();
        let mut value =
            json!({"baseline":baseline,"configuration":desired,"coverage":["/etc"],"restore":{}});
        restore(&store, &mut value, true).unwrap();
        assert_eq!(
            fs::read_to_string(root.join("etc/edit")).unwrap(),
            "local\n"
        );
        assert_eq!(
            fs::metadata(root.join("etc/edit")).unwrap().mode() & 0o7777,
            0o600
        );
        assert!(!root.join("etc/delete").exists());
        assert_eq!(
            fs::read_to_string(root.join("etc/new-security-default")).unwrap(),
            "new\n"
        );
        fs::write(root.join("etc/edit"), "new base conflict\n").unwrap();
        assert!(restore(&store, &mut value, true).is_err());
        assert_eq!(
            fs::read_to_string(root.join("etc/edit")).unwrap(),
            "new base conflict\n"
        );
        assert_eq!(
            value["restore"]["configuration_conflicts"],
            json!(["/etc/edit"])
        );
    }

    #[test]
    fn coverage_does_not_follow_links_or_capture_generated_identity() {
        let temporary = tempfile::tempdir().unwrap();
        fs::create_dir_all(temporary.path().join("etc")).unwrap();
        fs::write(
            temporary.path().join("etc/environment"),
            "secret runtime token",
        )
        .unwrap();
        fs::write(temporary.path().join("outside"), "uncovered").unwrap();
        std::os::unix::fs::symlink("../outside", temporary.path().join("etc/link")).unwrap();
        let files = inventory(temporary.path(), &["/etc".into()]).unwrap();
        assert!(files["/etc/environment"].is_null());
        assert_eq!(files["/etc/link"]["kind"], "symlink");
        assert_eq!(files.as_object().unwrap().len(), 2);
        assert!(validate_path("/etc/../home").is_err());
        assert!(validate_path("/").is_err());
    }
}
